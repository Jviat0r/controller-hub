//! Build-time guarantees for the bundled drivers:
//! 1. every installer named in drivers/manifest.json is present and matches
//!    its pinned size and SHA-256 (a hard error for release builds, a warning
//!    for dev builds so `cargo test` still works on a fresh clone);
//! 2. the NSIS installer hook is generated from the same manifest, so the
//!    installer can never run a file the app does not also know about.

use std::{env, fs, path::Path};

use controller_hub_core::bundle::{manifest, verify, InstallerSpec, Manifest};

fn main() {
    println!("cargo:rerun-if-changed=drivers/manifest.json");
    let m = manifest();
    let release = env::var("PROFILE").map(|p| p == "release").unwrap_or(false);
    let problems = check_files(&m);
    if !problems.is_empty() {
        if release {
            panic!(
                "bundled driver check failed; fix src-tauri/drivers before a release build:\n  {}",
                problems.join("\n  ")
            );
        }
        for p in &problems {
            println!("cargo:warning=bundled driver check: {p}");
        }
    }
    let hooks = render_hooks(&m);
    fs::create_dir_all("windows").expect("create windows dir");
    let path = Path::new("windows/hooks.nsh");
    if fs::read_to_string(path).map(|old| old != hooks).unwrap_or(true) {
        fs::write(path, hooks).expect("write windows/hooks.nsh");
    }
    tauri_build::build()
}

fn check_files(m: &Manifest) -> Vec<String> {
    let dir = Path::new("drivers");
    let mut problems = Vec::new();
    for spec in &m.installers {
        println!("cargo:rerun-if-changed=drivers/{}", spec.file);
        println!("cargo:rerun-if-changed=drivers/{}", spec.license);
        match fs::read(dir.join(&spec.file)) {
            Ok(bytes) => {
                if let Err(e) = verify(spec, &bytes) {
                    problems.push(format!("{}: {e}", spec.file));
                }
            }
            Err(_) => problems.push(format!("{}: missing (download from {})", spec.file, spec.source)),
        }
        if !dir.join(&spec.license).exists() {
            problems.push(format!("{}: licence file {} is missing", spec.name, spec.license));
        }
    }
    problems
}

fn install_block(spec: &InstallerSpec) -> String {
    format!(
        r#"  DetailPrint "Installing {name} {version}..."
  ExecWait '"$INSTDIR\drivers\{file}" {args}' $0
  DetailPrint "{name} setup finished with code $0"
  ${{If}} $0 == 3010
    StrCpy $DriverRebootNeeded "1"
  ${{EndIf}}
"#,
        name = spec.name,
        version = spec.version,
        file = spec.file,
        args = spec.silent_args,
    )
}

fn render_hooks(m: &Manifest) -> String {
    let required: Vec<&InstallerSpec> = m.installers.iter().filter(|s| s.required).collect();
    let optional: Vec<&InstallerSpec> = m.installers.iter().filter(|s| !s.required).collect();

    let mut out = String::new();
    out.push_str("; Generated by src-tauri/build.rs from drivers/manifest.json. Do not edit by hand.\n");
    out.push_str("; Installs the bundled kernel drivers after the app files are in place.\n\n");
    out.push_str("Var DriverRebootNeeded\nVar InstallOptionalDrivers\n\n");

    // Pre-install: ask once about the optional drivers (defaults to yes in /S mode).
    out.push_str("!macro NSIS_HOOK_PREINSTALL\n");
    out.push_str("  StrCpy $DriverRebootNeeded \"0\"\n");
    out.push_str("  StrCpy $InstallOptionalDrivers \"1\"\n");
    if !optional.is_empty() {
        let names: Vec<String> = optional.iter().map(|s| format!("{} {}", s.name, s.version)).collect();
        let purposes: Vec<String> = optional.iter().map(|s| format!("{}: {}", s.name, s.purpose)).collect();
        out.push_str("  IfSilent +3\n");
        out.push_str(&format!(
            "  MessageBox MB_YESNO|MB_ICONQUESTION \"Also install {}?$\\r$\\n$\\r$\\n{}$\\r$\\n$\\r$\\nYou can skip this and add it later from the app's Settings.\" /SD IDYES IDYES +2\n",
            names.join(" and "),
            purposes.join("$\\r$\\n")
        ));
        out.push_str("  StrCpy $InstallOptionalDrivers \"0\"\n");
    }
    out.push_str("!macroend\n\n");

    // Post-install: run the setups silently; they self-elevate under the per-machine installer.
    out.push_str("!macro NSIS_HOOK_POSTINSTALL\n");
    for spec in &required {
        out.push_str(&install_block(spec));
    }
    if !optional.is_empty() {
        out.push_str("  ${If} $InstallOptionalDrivers == \"1\"\n");
        for spec in &optional {
            for line in install_block(spec).lines() {
                out.push_str("  ");
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push_str("  ${EndIf}\n");
    }
    out.push_str("  ${If} $DriverRebootNeeded == \"1\"\n");
    out.push_str("    SetRebootFlag true\n");
    out.push_str("    IfSilent +2\n");
    out.push_str("    MessageBox MB_OK|MB_ICONINFORMATION \"A driver needs a restart before it works. Restart Windows when convenient.\" /SD IDOK\n");
    out.push_str("  ${EndIf}\n");
    out.push_str("!macroend\n\n");

    // Pre-uninstall: never leave a controller invisible after the app is gone.
    out.push_str("!macro NSIS_HOOK_PREUNINSTALL\n");
    out.push_str("  IfFileExists \"$PROGRAMFILES64\\Nefarius Software Solutions\\HidHide\\x64\\HidHideCLI.exe\" 0 +3\n");
    out.push_str("    ExecWait '\"$PROGRAMFILES64\\Nefarius Software Solutions\\HidHide\\x64\\HidHideCLI.exe\" --app-unreg \"$INSTDIR\\${MAINBINARYNAME}.exe\"'\n");
    out.push_str("    ExecWait '\"$PROGRAMFILES64\\Nefarius Software Solutions\\HidHide\\x64\\HidHideCLI.exe\" --cloak-off'\n");
    out.push_str("!macroend\n\n");

    out.push_str("!macro NSIS_HOOK_POSTUNINSTALL\n");
    out.push_str("  ; The drivers stay installed: other apps (DS4Windows, Steam) may rely on them.\n");
    out.push_str("!macroend\n");
    out
}
